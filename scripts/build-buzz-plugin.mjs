import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const ids = ['sales-drop-diagnostic', 'ad-waste-audit', 'catalog-foundation-scan', 'listing-conversion-diagnosis', 'competitive-keyword-gap-snapshot'];
const data = {
  instructions: read('agent-operating-instructions.md'),
  guardrails: read('operator-guardrails.md'),
  recommendation: read('templates/recommendation-output.md'),
  feedback: read('templates/feedback-log.md'),
  license: read('LICENSE'),
  workflows: ids.map(id => {
    const text = read(`skills/${id}.md`);
    return { id, title: text.split('\n')[0].replace('# Skill: ', ''), text };
  }),
};
const runtime = read('plugins/buzz/runtime.txt');
const output = '// Generated by scripts/build-buzz-plugin.mjs. Edit runtime.txt or source Markdown.\n' +
  'export const inject = ["react", "pages", "agents"];\n\nexport function apply(ctx) {\n' +
  `  const pack = ${JSON.stringify(data, null, 2)};\n` + runtime + '\n}\n';
const target = new URL('plugins/buzz/plugin.js', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('plugin.js is stale; run node scripts/build-buzz-plugin.mjs');
} else {
  writeFileSync(target, output);
  console.log(`Built ${fileURLToPath(target)}`);
}
